
import json
import re
from typing import Any, Optional

from ..config import settings
from .recommendations import (
    demo_home,
    demo_party,
    demo_jewelry,
    marketplace_link,
)

try:
    from google import genai
    from google.genai import types
except ImportError:
    genai = None
    types = None


_client = None


def get_client():
    """Create the Gemini client if an API key is configured."""
    global _client

    api_key = settings.gemini_api_key

    if not api_key or genai is None:
        return None

    if _client is None:
        _client = genai.Client(api_key=api_key)

    return _client


def _prompt(planner: str, data: dict) -> str:
    budget = data.get("budget", 0)

    return f"""
You are PocketSmart AI, a practical, budget-aware recommendation assistant.

Planner: {planner}

User information:
{json.dumps(data, ensure_ascii=False, default=str)}

Create a practical plan within the user's total budget.
Use Indian Rupees (INR).

Rules:
- Return only valid JSON, with no Markdown fences.
- Use estimated prices, not claimed live prices.
- Do not claim live stock or real-time marketplace data.
- Include 4 to 8 useful recommendations.
- Keep total estimated recommendation spending within the budget.
- Use realistic estimated prices.
- Marketplace links will be generated by the application.

Return this JSON structure:
{{
  "planner": "{planner}",
  "budget": {json.dumps(budget)},
  "summary": "A short useful summary",
  "allocations": {{
    "category": 0
  }},
  "recommendations": [
    {{
      "category": "Furniture",
      "title": "Product name",
      "platform": "Amazon",
      "estimated_price": 0,
      "reason": "Why this item is recommended",
      "link": ""
    }}
  ],
  "tips": ["Useful budget tip"]
}}
"""


def _extract_json(text: str) -> dict[str, Any]:
    """Extract a JSON object from Gemini's response."""
    if not text:
        raise ValueError("Gemini returned an empty response.")

    text = text.strip()

    text = re.sub(
        r"^\s*```(?:json)?\s*",
        "",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(r"\s*```\s*$", "", text).strip()

    try:
        result = json.loads(text)
        if isinstance(result, dict):
            return result
    except json.JSONDecodeError:
        pass

    start = text.find("{")
    end = text.rfind("}")

    if start < 0 or end <= start:
        raise ValueError("Gemini did not return a JSON object.")

    try:
        result = json.loads(text[start:end + 1])
    except json.JSONDecodeError as exc:
        raise ValueError(f"Gemini returned invalid JSON: {exc}") from exc

    if not isinstance(result, dict):
        raise ValueError("Gemini returned an invalid JSON structure.")

    return result


def _response_text(response: Any) -> str:
    """Extract text from a Gemini response."""
    try:
        value = response.text
        if value:
            return str(value).strip()
    except Exception:
        pass

    chunks = []

    for candidate in getattr(response, "candidates", None) or []:
        content = getattr(candidate, "content", None)
        if not content:
            continue

        for part in getattr(content, "parts", None) or []:
            value = getattr(part, "text", None)
            if value:
                chunks.append(str(value))

    return "\n".join(chunks).strip()


def _normalize(result: dict, planner: str, data: dict) -> dict:
    """Ensure the result has the fields expected by the application."""
    result.setdefault("planner", planner)
    result.setdefault("budget", data.get("budget", 0))
    result.setdefault("summary", "Your personalized PocketSmart AI plan.")
    result.setdefault("allocations", {})
    result.setdefault("recommendations", [])
    result.setdefault("tips", [])

    if not isinstance(result["recommendations"], list):
        raise ValueError("Recommendations must be a list.")

    valid_recommendations = []

    for item in result["recommendations"]:
        if not isinstance(item, dict):
            continue

        item.setdefault("category", "General")
        item.setdefault("title", "Recommended item")
        item.setdefault("platform", "Amazon")
        item.setdefault("reason", "Suitable for your requirements.")

        try:
            price = float(item.get("estimated_price", 0) or 0)
            item["estimated_price"] = max(0, price)
        except (ValueError, TypeError):
            item["estimated_price"] = 0

        item["link"] = marketplace_link(
            str(item.get("platform", "Amazon")),
            str(item.get("title", "product")),
        )

        valid_recommendations.append(item)

    result["recommendations"] = valid_recommendations
    result["demo_mode"] = False

    return result


def _fallback(planner: str, data: dict, error=None) -> dict:
    """Return demo recommendations when Gemini fails."""
    demo_functions = {
        "home": demo_home,
        "party": demo_party,
        "jewelry": demo_jewelry,
    }

    if planner not in demo_functions:
        raise ValueError(f"Unknown planner: {planner}")

    result = demo_functions[planner](data)
    result["demo_mode"] = True

    if error is not None:
        result["summary"] = (
            "Demo fallback is active because Gemini failed. "
            f"Error type: {type(error).__name__}. "
            "Check the VS Code terminal for GEMINI ERROR details."
        )

    return result


def _generate_with_gemini(planner: str, data: dict, image_bytes=None, mime_type=None):
    client = get_client()

    if client is None:
        print(
            "GEMINI ERROR: No client available. "
            "Check your API key, .env configuration, and google-genai installation."
        )
        return _fallback(planner, data)

    if types is None:
        print("GEMINI ERROR: google.genai.types could not be imported.")
        return _fallback(planner, data)

    try:
        prompt = _prompt(planner, data)
        contents = []

        if image_bytes:
            contents.append(
                types.Part.from_bytes(
                    data=image_bytes,
                    mime_type=mime_type or "image/jpeg",
                )
            )

        contents.append(prompt)

        config = types.GenerateContentConfig(
            temperature=0.2,
            max_output_tokens=2500,
            response_mime_type="application/json",
        )

        response = client.models.generate_content(
            model=settings.gemini_model,
            contents=contents,
            config=config,
        )

        raw_text = _response_text(response)
        result = _extract_json(raw_text)

        return _normalize(result, planner, data)

    except Exception as exc:
        # Diagnostic: show the real cause in the VS Code terminal.
        print(f"GEMINI ERROR: {type(exc).__name__}: {exc!s}")
        return _fallback(planner, data, exc)


def generate_text(planner: str, data: dict):
    """Generate a home or party plan, or a text-only jewelry plan."""
    return _generate_with_gemini(planner, data)


def generate_jewelry(
    data: dict,
    image_bytes: Optional[bytes] = None,
    mime_type: Optional[str] = None,
):
    """Generate jewelry recommendations, optionally using an outfit image."""
    return _generate_with_gemini(
        "jewelry",
        data,
        image_bytes=image_bytes,
        mime_type=mime_type,
    )
